def dump(path,data):Path(path).write_text(json.dumps(data,indent=2,ensure_ascii=False)+'\n')
def load(path):return json.loads(Path(path).read_text())
def manifest_path(profile):return Path(profile).resolve().parent/'character-workspace.json'
def init_workspace(inputs,out):
    out=Path(out).resolve()
    if out.exists():raise ValueError('New output directory required')
    if set(inputs)!=set(VIEWS):raise ValueError('All three original views required')
    for view in VIEWS:
        with Image.open(inputs[view]) as im:
            if im.format!='PNG' or im.width<1 or im.height<1:raise ValueError('Readable PNG originals required')
    out.mkdir(parents=True);(out/'inputs').mkdir();sources={}
    for view in VIEWS:
        dest=out/'inputs'/f'{view}.png';shutil.copyfile(inputs[view],dest)
        sources[view]={'path':str(dest.relative_to(out)),'sha256':drawn_cel.digest(dest)}
    profile={'schema':'character-profile/1','identity':{'descriptors':None},'proportions':{'notes':None},'clothing':None,'accessories':None,
       'contacts':{'armMode':None,'held':None},'timing':{'durationsMs':None,'phases':None},
       'views':{v:{'facing':v if v!='side' else None,'representation':None,'contacts':None,'occlusionNotes':None,'armSurfaceSpec':None,'ownership':{'basis':None,'ownerA':None,'ownerB':None}} for v in VIEWS},
       'instructions':'Inspect originals; fill decisions from this character, not another character template. Explicit empty lists mean none. No poses are generated by this file. For each view, consider armSurfaceSpec: physical arm identity, visible hand surface from the original/user request, pose and held contacts, sleeve or bare-shoulder boundary, elbow/wrist continuity, and occlusion. Null means these decisions are unrecorded, never an instruction to show palms.'}
    path=out/'character-profile.json';dump(path,profile);dump(out/'character-workspace.json',{'schema':'character-workspace/1','sources':sources,'bindings':{}});return path

def read_workspace(profile):
    profile=Path(profile).resolve();p=load(profile);m=load(manifest_path(profile));root=profile.parent
    if p.get('schema')!='character-profile/1' or m.get('schema')!='character-workspace/1':raise ValueError('Unsupported character workspace schema')
    if set(m.get('sources',{}))!=set(VIEWS):raise ValueError('Three immutable source entries required')
    for v,source in m['sources'].items():
        q=drawn_cel.confined(root,source['path'])
        if drawn_cel.digest(q)!=source['sha256']:raise ValueError('Original source changed: '+v)
    return profile,p,m

def validate_contacts(c):
    if not isinstance(c,dict) or c.get('armMode') not in ('free','held','none') or not isinstance(c.get('held'),list) or any(not isinstance(x,str) or not x.strip() for x in c.get('held',[])):raise ValueError('Missing arm/contact decision')
    if (c['armMode']=='held') != bool(c['held']):raise ValueError('Held arm mode requires held contacts; other modes must have none')

ARM_SURFACES={'palm','dorsal','edge','occluded','source-dependent'}
ARM_FIELDS={'physicalArmId','visibleHandSurface','mode','pose','contacts','shoulderBoundary','elbowContinuity','wristContinuity','occlusionExpectation'}

def validate_arm_surface_spec(spec,contacts):
    """Validate authored intent, not arm anatomy, hand recognition, or visual quality."""
    if spec is None:return
    if not isinstance(spec,dict) or set(spec)!={'arms'} or not isinstance(spec['arms'],list):raise ValueError('armSurfaceSpec must contain an arms list, or be null')
    arms=spec['arms'];ids=set();modes=[]
    if not arms and contacts['armMode']!='none':raise ValueError('armSurfaceSpec must describe physical arms unless armMode is none')
    for arm in arms:
        if not isinstance(arm,dict) or set(arm)!=ARM_FIELDS:raise ValueError('armSurfaceSpec arm fields are missing or unknown')
        for key in ARM_FIELDS-{'contacts'}:
            if not isinstance(arm[key],str) or not arm[key].strip():raise ValueError('armSurfaceSpec requires nonempty '+key)
        identity=arm['physicalArmId'].strip()
        if identity in ids:raise ValueError('Duplicate physicalArmId in armSurfaceSpec')
        ids.add(identity)
        if arm['visibleHandSurface'] not in ARM_SURFACES:raise ValueError('Invalid visibleHandSurface; do not assume palms')
        validate_contacts({'armMode':arm['mode'],'held':arm['contacts']});modes.append(arm['mode'])
    overall=contacts['armMode']
    if (overall=='held' and 'held' not in modes) or (overall=='free' and 'free' not in modes) or (overall!='held' and 'held' in modes) or (overall=='none' and any(mode!='none' for mode in modes)):
        raise ValueError('armSurfaceSpec modes contradict resolved per-view contacts')

def arm_surface_request(row):
    spec=row.get('armSurfaceSpec')
    return {'armSurfaceSpec':spec,'armSurfaceReview':{
       'status':'unrecorded' if spec is None else 'specified-not-visually-validated',
       'requirements':['Keep each physical arm identity through occlusion; screen-near/far is not a replacement for physical identity.',
          'Visible hand surface follows the original and explicit per-arm instruction. Do not turn every hand into a palm.',
          'Preserve each specified pose/contact and source sleeve or bare-shoulder boundary. Inspect shoulder, elbow and wrist continuity in actual frames.',
          'Do not fabricate hidden hand surfaces. Mark uncertainty or source-dependent surfaces for actual-source review.'],
       'automaticSemanticValidation':False}}

def decisions(profile):
    _,p,_=read_workspace(profile)
    desc=p.get('identity',{}).get('descriptors')
    if not isinstance(desc,list) or not desc or any(not isinstance(x,str) or not x.strip() for x in desc):raise ValueError('Missing identity descriptors decision')
    if not isinstance(p.get('proportions',{}).get('notes'),str) or not p['proportions']['notes'].strip():raise ValueError('Missing proportions notes decision')
    for key,fields in [('clothing',('name','boundary','length')),('accessories',('name','behavior'))]:
        if not isinstance(p.get(key),list):raise ValueError('Missing '+key+' decision (explicit [] means none)')
        for item in p[key]:
            if not isinstance(item,dict) or any(not isinstance(item.get(f),str) or not item[f].strip() for f in fields):raise ValueError('Incomplete '+key+' descriptor')
            if key=='accessories' and item['behavior'] not in ('rigid','flexible'):raise ValueError('Accessory behavior must be rigid or flexible')
    c=p.get('contacts',{})
    validate_contacts(c)
    d=p.get('timing',{}).get('durationsMs');ph=p.get('timing',{}).get('phases')
    if not isinstance(d,list) or len(d)<4 or len(d)>256 or len(d)%2 or any(type(x)is not int or x<=0 or x%10 for x in d):raise ValueError('Timing needs an even count of positive GIF-multiple durations')
    if not isinstance(ph,list) or len(ph)!=len(d) or any(x not in drawn_cel.PHASES for x in ph):raise ValueError('Explicit phase per cel required')
    if ph[0]!='contact' or ph[len(ph)//2]!='contact' or ph.count('contact')!=2:raise ValueError('Two half-cycles must start at contact; label intermediate poses explicitly')
    if set(p.get('views',{}))!=set(VIEWS):raise ValueError('All three view decisions required')
    for v,row in p['views'].items():
        if row.get('contacts') is not None:validate_contacts(row['contacts'])
        validate_arm_surface_spec(row.get('armSurfaceSpec'),row['contacts'] if row.get('contacts') is not None else c)
        if row.get('occlusionNotes') is not None and not isinstance(row['occlusionNotes'],str):raise ValueError('occlusionNotes must be a string or null')
        if row.get('facing') not in ({'left','right'} if v=='side' else {v}):raise ValueError('Missing or mismatched facing: '+v)
        if row.get('representation') not in REPRESENTATIONS:raise ValueError('Missing representation: '+v)
        o=row.get('ownership',{})
        if v in ('front','back') and o.get('basis')!='anatomical-left-right':raise ValueError('Front/back require anatomical-left-right ownership basis: '+v)
        if o.get('basis') not in ('near-far','anatomical-left-right') or any(not isinstance(o.get(k),str) or not o[k].strip() for k in ('ownerA','ownerB')) or o['ownerA']==o['ownerB']:raise ValueError('Explicit two-leg ownership basis required: '+v)
    return p

def intake_fingerprint(profile):
    _,p,m=read_workspace(profile)
    return hashlib.sha256(json.dumps({'profile':p,'sources':m['sources']},sort_keys=True).encode()).hexdigest()
def intake_path(profile):return Path(profile).resolve().parent/'intake-review.json'
def record_intake(profile,evidence,note):
    decisions(profile)
    if not isinstance(note,str) or len(note.strip())<12:raise ValueError('Meaningful human identity/intake note required')
    evidence=Path(evidence).resolve()
    if not evidence.is_file():raise ValueError('Missing intake evidence')
    root=Path(profile).resolve().parent;sha=drawn_cel.digest(evidence);dest=root/'intake-evidence'/(sha+evidence.suffix);dest.parent.mkdir(exist_ok=True)
    if not dest.exists():shutil.copyfile(evidence,dest)
    row={'fingerprint':intake_fingerprint(profile),'evidence':str(dest.relative_to(root)),'sha256':sha,'note':note.strip(),'kind':'human source identity and per-view design assertion; not automatic recognition'};dump(intake_path(profile),row);return row

def require_intake(profile):
    decisions(profile)
    try:
        row=load(intake_path(profile));root=Path(profile).resolve().parent
        valid=row['fingerprint']==intake_fingerprint(profile) and drawn_cel.digest(drawn_cel.confined(root,row['evidence']))==row['sha256']
    except (KeyError,OSError,ValueError):valid=False
    if not valid:raise ValueError('Missing or stale source identity/intake review')

def planned_phases(p,view):
    o=p['views'][view]['ownership'];half=len(p['timing']['phases'])//2
    return [{'phase':phase,'supportOwner':o['ownerA'] if i<half else o['ownerB'],'swingOwner':o['ownerB'] if i<half else o['ownerA']} for i,phase in enumerate(p['timing']['phases'])]

